_SKIN_TONES = ("🏻", "🏼", "🏽", "🏾", "🏿")

_PACK_BY_NORM: dict[str, str] = {}
for _emo, _eid in PACK_IDS.items():
    _PACK_BY_NORM.setdefault(_emo.replace("\ufe0f", ""), _emo)

_ALIAS_BY_NORM: dict[str, str] = {}
for _src, _dst in ALIASES.items():
    _ALIAS_BY_NORM.setdefault(_src.replace("\ufe0f", ""), _dst)


def _norm(token: str) -> str:
    return token.replace("\ufe0f", "")


def resolve(token: str) -> Optional[tuple[str, str]]:
    """Вернуть (custom_emoji_id, канонический эмодзи пака) или None."""
    if token in PACK_IDS:
        return PACK_IDS[token], token
    packed = _PACK_BY_NORM.get(_norm(token))
    if packed:
        return PACK_IDS[packed], packed
    alias = ALIASES.get(token) or _ALIAS_BY_NORM.get(_norm(token))
    if alias:
        if alias in PACK_IDS:
            return PACK_IDS[alias], alias
        packed = _PACK_BY_NORM.get(_norm(alias))
        if packed:
            return PACK_IDS[packed], packed
    return None


def html(token: str) -> str:
    found = resolve(token)
    if not found:
        return token
    eid, canon = found
    return f'<tg-emoji emoji-id="{eid}">{canon}</tg-emoji>'


_TOKEN_KEYS = sorted(
    set(PACK_IDS) | set(ALIASES) | set(KEYCAP_TO_DIGIT),
    key=len,
    reverse=True,
)
_TOKEN_RE = re.compile("|".join(re.escape(k) for k in _TOKEN_KEYS))
_EXISTING_TAG_RE = re.compile(r"<tg-emoji emoji-id=\"\d+\">.*?</tg-emoji>", re.DOTALL)
_HTML_TAG_RE = re.compile(r"<[^>]+>")
_KEYCAP_RE = re.compile("|".join(re.escape(k) for k in sorted(KEYCAP_TO_DIGIT, key=len, reverse=True)))
_MULTI_SPACE_RE = re.compile(r"[ \t]{2,}")


def emojify(text: str) -> str:
    """Заменить эмодзи в HTML-тексте на <tg-emoji>. Идемпотентно."""
    if not text:
        return text
    placeholders: list[str] = []

    def _hold(match: re.Match[str]) -> str:
        placeholders.append(match.group(0))
        return f"\x00{len(placeholders) - 1}\x00"

    protected = _EXISTING_TAG_RE.sub(_hold, text)
    protected = _HTML_TAG_RE.sub(_hold, protected)

    def _repl(match: re.Match[str]) -> str:
        token = match.group(0)
        if token == "🔟":
            return "10"
        if token in _SKIN_TONES:
            return ""
        found = resolve(token)
        if not found:
            return token
        eid, canon = found
        return f'<tg-emoji emoji-id="{eid}">{canon}</tg-emoji>'

    converted = _TOKEN_RE.sub(_repl, protected)
    for i, raw in enumerate(placeholders):
        converted = converted.replace(f"\x00{i}\x00", raw)
    return converted


def emojify_value(value: Any) -> Any:
    if isinstance(value, str):
        return emojify(value)
    if isinstance(value, tuple):
        return tuple(emojify_value(v) for v in value)
    if isinstance(value, list):
        return [emojify_value(v) for v in value]
    if isinstance(value, dict):
        return {k: emojify_value(v) for k, v in value.items()}
    return value


def _strip_known_emojis(text: str) -> str:
    text = _KEYCAP_RE.sub(lambda m: KEYCAP_TO_DIGIT[m.group(0)], text)
    text = _TOKEN_RE.sub("", text)
    for tone in _SKIN_TONES:
        text = text.replace(tone, "")
    text = _MULTI_SPACE_RE.sub(" ", text)
    return text.strip()


def apply_button_icon(text: str) -> tuple[str, Optional[str]]:
    """Убрать эмодзи из текста кнопки и вернуть icon_custom_emoji_id."""
    if not text:
        return text, None
    leading = _TOKEN_RE.match(text)
    eid: Optional[str] = None
    rest = text
    if leading:
        found = resolve(leading.group(0))
        if found:
            eid = found[0]
        rest = text[leading.end() :]
    else:
        matches = list(_TOKEN_RE.finditer(text))
        if matches:
            last = matches[-1]
            if last.end() == len(text.rstrip()) or text[last.end() :].strip() == "":
                found = resolve(last.group(0))
                if found:
                    eid = found[0]
                rest = text[: last.start()] + text[last.end() :]
    rest = _strip_known_emojis(rest)
    if not rest:
        rest = _strip_known_emojis(text) or text
    return rest, eid


def emoji_button(**kwargs: Any) -> InlineKeyboardButton:
    text = kwargs.get("text") or ""
    if not kwargs.get("icon_custom_emoji_id"):
        clean, eid = apply_button_icon(str(text))
        kwargs["text"] = clean
        if eid:
            kwargs["icon_custom_emoji_id"] = eid
    return InlineKeyboardButton(**kwargs)


def emoji_reply_button(**kwargs: Any) -> KeyboardButton:
    text = kwargs.get("text") or ""
    if not kwargs.get("icon_custom_emoji_id"):
        clean, eid = apply_button_icon(str(text))
        kwargs["text"] = clean
        if eid:
            kwargs["icon_custom_emoji_id"] = eid
    return KeyboardButton(**kwargs)
